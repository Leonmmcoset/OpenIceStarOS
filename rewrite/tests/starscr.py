"""Compare original and recovered STARSCR.X, including the real SDK wrappers."""
import hashlib
import json
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
from kernel_image import Fat16
from xformat import XImage


def main():
    build = ROOT / "build"
    original = Fat16((ROOT.parent / "IceStarOS_x86_32M.vhd").read_bytes()).read_file(
        b"ICESTAR    ", b"STARSCR X  ")
    assert hashlib.sha256(original).hexdigest() == "6d2f3ebfe9a45dcba055ddfe01b7fb8f384e0003a9a9484c9585d912c7f0473c"
    rewritten = (build / "starscr.x").read_bytes()
    symbols = json.loads((build / "starscr.symbols.json").read_text())["symbols"]
    for data in (original, rewritten):
        image = XImage(data)
        assert (image.header[0], len(data), image.entry, image.bss_start,
                image.bss_size, image.header[3]) == (10, 0x3eb4, 0x40, 0x3ddc, 16, 16)
        assert data[0x3dd0:0x3ddc] == original[0x3dd0:0x3ddc]
    assert len(XImage(original).relocations) == 54
    assert len(XImage(rewritten).relocations) == 21
    assert symbols["starscr_state"]["address"] == 0x3ddc
    assert symbols["starscr_title"]["address"] == 0x3dd0
    names = ("starscr_entry", "starscr_key", "starscr_close", "starscr_draw")
    header = "/* Generated by tests/starscr.py. */\n"
    header += "static const unsigned original_functions[] = {0x40,0x160,0x180,0x198};\n"
    header += "static const unsigned rewritten_functions[] = {" + ",".join(
        hex(symbols[name]["address"]) for name in names) + "};\n"
    (build / "starscr_bindings.h").write_text(header)
    (build / "starscr.original.x").write_bytes(original)
    subprocess.run(["gcc", "-m32", "-march=i386", "-Os", "-ffreestanding", "-nostdlib", "-static",
                    "-fno-pic", "-fno-pie", "-fno-stack-protector", "-fno-asynchronous-unwind-tables",
                    "-fno-optimize-sibling-calls", "-Wall", "-Wextra", "-Werror", "-Ibuild", "-Wl,-e,_start",
                    "tests/starscr.c", "-o", "build/starscr_test"], cwd=ROOT, check=True)
    subprocess.run(["build/starscr_test"], cwd=ROOT, check=True)


if __name__ == "__main__":
    main()
