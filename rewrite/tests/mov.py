"""Execute the original and C MOV.X through their unmodified SDK wrappers."""

import hashlib
import json
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
from kernel_image import Fat16
from xformat import XImage


def main():
    build = ROOT / "build"
    original = Fat16((ROOT.parent / "IceStarOS_x86_32M.vhd").read_bytes()).read_file(
        b"ICESTAR    ", b"GAMES      ", b"MOV        ", b"MOV     X  ")
    assert hashlib.sha256(original).hexdigest() == "df5429c3e1ff472e0c6142fa003635430eef3114a6fcd256c14319ac83199a68"
    rewritten = (build / "mov.x").read_bytes()
    symbols = json.loads((build / "mov.symbols.json").read_text())["symbols"]
    for data in (original, rewritten):
        image = XImage(data)
        assert (image.header[0], len(data), image.entry, image.bss_start,
                image.bss_size, image.header[3], len(image.relocations)) == (
                    10, 0x3a54, 0x40, 0x3a14, 16, 16, 16)
        assert data[0x3990:0x3a14] == original[0x3990:0x3a14]
    assert symbols["mov_frames"]["address"] == 0x3a14
    assert symbols["mov_strings"]["address"] == 0x3990
    names = ("mov_entry", "mov_close")
    header = "/* Generated by tests/mov.py. */\n"
    header += "static const unsigned original_functions[] = {0x40,0x262};\n"
    header += "static const unsigned rewritten_functions[] = {" + ",".join(
        hex(symbols[name]["address"]) for name in names) + "};\n"
    (build / "mov_bindings.h").write_text(header)
    (build / "mov.original.x").write_bytes(original)
    subprocess.run(["gcc", "-m32", "-march=i386", "-Os", "-ffreestanding", "-nostdlib", "-static",
                    "-fno-pic", "-fno-pie", "-fno-stack-protector", "-fno-asynchronous-unwind-tables",
                    "-Wall", "-Wextra", "-Werror", "-Ibuild", "-Wl,-e,_start",
                    "tests/mov.c", "-o", "build/mov_test"], cwd=ROOT, check=True)
    subprocess.run(["build/mov_test"], cwd=ROOT, check=True)


if __name__ == "__main__":
    main()
