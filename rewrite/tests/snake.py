"""Execute original and C-built SNAKE.X after relocating both flat images."""

import hashlib
import json
from pathlib import Path
import struct
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
from kernel_image import Fat16
from xformat import XImage


def main():
    build = ROOT / "build"
    original = Fat16((ROOT.parent / "IceStarOS_x86_32M.vhd").read_bytes()).read_file(
        b"ICESTAR    ", b"GAMES      ", b"SNAKE   X  ")
    assert hashlib.sha256(original).hexdigest() == "be2bbb4d1369977369bdc5292a29d0f02350d92bf4207e9f6123466c6f570488"
    rewritten = (build / "snake.x").read_bytes()
    metadata = json.loads((build / "snake.symbols.json").read_text())
    symbols = metadata["symbols"]
    functions = [("snake_cell", 0x40), ("snake_food", 0xa8), ("snake_reset", 0x102),
                 ("snake_move", 0x182), ("snake_draw", 0x2ac), ("snake_key", 0x4ca),
                 ("snake_entry", 0x5dc)]
    apis = [("rectangle", 0x7dc), ("text", 0x83e), ("window_create", 0x876),
            ("service_40_13", 0x884), ("service_40_16", 0x8ae), ("service_40_17", 0x8bc),
            ("events", 0x8ca), ("service_41_01", 0x8d8), ("surface", 0x8e6),
            ("color", 0x8f4), ("random", 0x902), ("ticks", 0x910)]
    for name, address in apis:
        symbol = symbols["x_" + name]
        assert symbol["size"] == 14, (name, "interrupt stub size changed")
        assert rewritten[symbol["address"]:symbol["address"] + 14] == original[address:address + 14], name
    for data in (original, rewritten):
        parsed = XImage(data)
        assert (parsed.bss_start, parsed.bss_size, parsed.header[3]) == (0x980, 0x380, 16)
    header = "/* Generated by tests/snake.py. */\n"
    header += "static const unsigned original_functions[] = {" + ",".join(hex(a) for _, a in functions) + "};\n"
    header += "static const unsigned rewritten_functions[] = {" + ",".join(hex(symbols[n]["address"]) for n, _ in functions) + "};\n"
    header += "static const unsigned original_apis[] = {" + ",".join(hex(a) for _, a in apis) + "};\n"
    header += "static const unsigned rewritten_apis[] = {" + ",".join(hex(symbols["x_" + n]["address"]) for n, _ in apis) + "};\n"
    (build / "snake_bindings.h").write_text(header)
    (build / "snake.original.x").write_bytes(original)
    subprocess.run(["gcc", "-m32", "-march=i386", "-Os", "-ffreestanding", "-nostdlib", "-static",
                    "-fno-pic", "-fno-pie", "-fno-stack-protector", "-fno-asynchronous-unwind-tables",
                    "-Wall", "-Wextra", "-Werror", "-Ibuild", "-Wl,-e,_start",
                    "tests/snake.c", "-o", "build/snake_test"], cwd=ROOT, check=True)
    subprocess.run(["build/snake_test"], cwd=ROOT, check=True)
    print("All twelve compiled interrupt stubs exactly match the original 14-byte boundaries")


if __name__ == "__main__":
    main()
