"""Execute original and C-recovered COLOR.X through the real shared-table ABI."""

import hashlib
import json
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
from kernel_image import Fat16
from xformat import XImage


def main():
    build = ROOT / "build"
    original = Fat16((ROOT.parent / "IceStarOS_x86_32M.vhd").read_bytes()).read_file(
        b"ICESTAR    ", b"COLOR   X  ")
    assert hashlib.sha256(original).hexdigest() == "b693c210f98a8295d5cad90b2370302b1a527c895bdca23d925b40d18773c6c3"
    rewritten = (build / "color.x").read_bytes()
    metadata = json.loads((build / "color.symbols.json").read_text())
    symbols = metadata["symbols"]
    for data in (original, rewritten):
        image = XImage(data)
        assert (image.header[0], len(data), image.bss_start, image.bss_size,
                image.header[3], len(image.relocations)) == (10, 0x38b4, 0x3898, 16, 16, 7)
        assert data[0x3890:0x3898] == b"\xd1\xd5\xc9\xab\0\0\0\0"
    assert symbols["color_state"]["address"] == 0x3898
    names = ("color_entry", "color_close", "color_draw")
    header = "/* Generated by tests/color.py. */\n"
    header += "static const unsigned original_functions[] = {0x40,0xe6,0xfe};\n"
    header += "static const unsigned rewritten_functions[] = {" + ",".join(
        hex(symbols[name]["address"]) for name in names) + "};\n"
    (build / "color_bindings.h").write_text(header)
    (build / "color.original.x").write_bytes(original)
    subprocess.run(["gcc", "-m32", "-march=i386", "-Os", "-ffreestanding", "-nostdlib", "-static",
                    "-fno-pic", "-fno-pie", "-fno-stack-protector", "-fno-asynchronous-unwind-tables",
                    "-Wall", "-Wextra", "-Werror", "-Ibuild", "-Wl,-e,_start",
                    "tests/color.c", "-o", "build/color_test"], cwd=ROOT, check=True)
    subprocess.run(["build/color_test"], cwd=ROOT, check=True)


if __name__ == "__main__":
    main()
